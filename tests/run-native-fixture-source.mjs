import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(resolve(root,p),'utf8');
const native=read('apps/desktop/src-tauri/src/chat_fixture_native.rs');
const injected=read('apps/desktop/src-tauri/src/chat_fixture_send.js');
const extension=read('apps/desktop/browser-extension/content-script.js');
const manifest=JSON.parse(read('apps/desktop/browser-extension/manifest.json'));
let count=0;
const yes=(value,label)=>{assert.ok(value,label);count++;};
const eq=(a,b,label)=>{assert.deepEqual(a,b,label);count++;};
yes(native.includes('LAZY_FIXTURE_BRIDGE_ENABLE'),'explicit debug opt-in');
yes(native.includes('cfg!(debug_assertions)'),'release disabled');
yes(native.includes('"CHAT_FIXTURE_BRIDGE_DISABLED"'),'default denies');
yes(native.includes('fixture_origin(&url).ok_or("FIXTURE_ORIGIN_REQUIRED")'),'origin checked natively');
yes(native.includes('url.host_str()? != "127.0.0.1"'),'loopback only');
yes(native.includes('"/fixture-chat/"'),'owned path only');
yes(/active\.insert\(\s*input\.workspace_id\.clone\(\),\s*Attempt/.test(native),'reserve before any browser side effect');
yes(native.search(/active\.insert\(\s*input\.workspace_id\.clone\(\),\s*Attempt/)<native.indexOf('view.eval(script)'),'reservation before page eval');
yes(native.includes('"SEND_OUTCOME_UNKNOWN"'),'uncertain side effect held');
yes(native.includes('"nextPromptAllowed":false'),'no automatic next prompt');
yes(native.includes('"sourceVerified":false'),'cannot forge source proof');
yes(native.includes('"observationTrusted":false'),'page observation is untrusted');
yes(native.includes('if url.as_str() != attempt.url'),'navigation mismatch blocked');
yes(native.includes('"FIXTURE_CONCURRENCY_LIMIT"'),'two active scope bound');
yes(native.includes('"FIXTURE_PROMPT_ALREADY_PENDING"'),'one prompt outstanding');
yes(native.includes('include_str!("chat_fixture_send.js")'),'native embeds fixed verified JS source');
yes(native.includes('serde_json::to_string(&packet)'),'user input serialized safely');
yes(native.includes('"expectedOrigin":origin'),'host supplies expected origin');
yes(native.includes('"expectedHref":url_string'),'host binds exact current URL');
yes(!native.includes('window.postMessage'),'old spoofable page-message route removed');
yes(!native.includes('"LP_FIXTURE_NATIVE_REQUEST"'),'old fake native request removed');
yes(!native.includes('getrandom::getrandom'),'no nonce shared with page');
yes(injected.includes('location.href !== input.expectedHref'),'DOM rechecks URL at execution');
yes(injected.includes('root.dataset.lpFixtureLastPrompt = key'),'fixture duplicate marker');
yes(injected.includes("send.click()"),'explicit Send button');
yes(!injected.includes('/backend-api/'),'no private endpoint');
yes(!injected.includes('assistantText'),'no output extraction');
yes(!extension.includes('window.addEventListener(\'message\''),'extension cannot accept page commands');
yes(!extension.includes('LP_FIXTURE_NATIVE_REQUEST'),'extension has no old native impersonation path');
eq(manifest.host_permissions,['http://127.0.0.1/*'],'extension only loopback');
eq(manifest.content_scripts[0].matches,['http://127.0.0.1/*'],'scope matcher unchanged');
yes(!JSON.stringify(manifest).includes('chatgpt.com'),'ChatGPT origin not permitted');
console.log('Native direct-send source contract: PASS ('+count+' assertions, Rust not compiled)');
