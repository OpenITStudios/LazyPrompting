import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const code=readFileSync(resolve(root,'apps/desktop/src-tauri/src/chat_fixture_native.rs'),'utf8');
const manifest=JSON.parse(readFileSync(resolve(root,'apps/desktop/browser-extension/manifest.json'),'utf8'));
const extension=readFileSync(resolve(root,'apps/desktop/browser-extension/content-script.js'),'utf8');
let count=0;
const yes=(value,msg)=>{assert.ok(value,msg);count++;};
const eq=(a,b,msg)=>{assert.deepEqual(a,b,msg);count++;};
yes(code.includes('LAZY_FIXTURE_BRIDGE_ENABLE'),'runtime flag required');
yes(code.includes('cfg!(debug_assertions)'),'debug only');
yes(code.includes('"CHAT_FIXTURE_BRIDGE_DISABLED"'),'feature default disabled');
yes(code.includes('fixture_origin(&url).ok_or("FIXTURE_ORIGIN_REQUIRED")'),'verify view origin');
yes(code.includes('url.host_str()? != "127.0.0.1"'),'no external site origin');
yes(code.includes('"/fixture-chat/"'),'local fixture path required');
yes(code.includes('LAZY_FIXTURE_BRIDGE_ENABLE'),'explicit opt-in');
yes(code.includes('active.insert(input.workspace_id.clone(), Attempt'),'reserve before side effects');
yes(code.indexOf('active.insert(input.workspace_id.clone(), Attempt')<code.indexOf('view.eval(script)'),'one attempt reserved before sending');
yes(code.includes('"SEND_OUTCOME_UNKNOWN"'),'ambiguous state remains unresolved');
yes(code.includes('"nextPromptAllowed":false'),'status cannot authorize next prompt');
yes(code.includes('"sourceVerified":false'),'no source verification claim');
yes(code.includes('"observationTrusted":false'),'DOM observation untrusted');
yes(code.includes('if url.as_str() != attempt.url'),'navigation invalidates session');
yes(code.includes('"FIXTURE_CONCURRENCY_LIMIT"'),'2 active cap');
yes(code.includes('"FIXTURE_PROMPT_ALREADY_PENDING"'),'one prompt per workspace');
yes(code.includes('"LP_FIXTURE_NATIVE_REQUEST"'),'native protocol request');
yes(code.includes('serde_json::to_string(&packet)'),'safe JSON serialization');
yes(code.includes('location.href !== {url_js}'),'revalidates exact URL on execution');
yes(code.includes('window.postMessage({packet_js}, {origin_js})'),'only owned window message');
yes(code.includes("document.querySelector('#status')"),'status checks fixture indicator only');
yes(!code.includes('document.querySelector(\'[data-message-author-role'),'no assistant output extraction');
eq(manifest.host_permissions,['http://127.0.0.1/*'],'fixture-only manifest');
eq(manifest.content_scripts[0].matches,['http://127.0.0.1/*'],'extension injected only loopback');
yes(!JSON.stringify(manifest).includes('chatgpt.com'),'no ChatGPT origin permission');
yes(extension.includes('LP_FIXTURE_NATIVE_REQUEST'),'extension handles host fixture messages');
yes(extension.includes('LP_FIXTURE_NATIVE_ACK'),'bounded non-authoritative acknowledgement');
yes(!extension.includes('/backend-api/'),'no private conversation endpoint');
console.log(`Native fixture source-contract: PASS (${count} assertions, source only; Rust NOT compiled)`);
